// Regenerates the mobile translation files from the shared dictionaries.
//
//   dart run tool/sync_l10n.dart
//
// Inputs:
//   ../../packages/shared/src/i18n/en.ts, hi.ts   (shared keys — source of truth)
//   tool/l10n/mobile_en.json, mobile_hi.json       (mobile-only keys)
// Outputs:
//   lib/l10n/app_en.arb, lib/l10n/app_hi.arb       (ARB, keys identical to the shared keys)
//   lib/l10n/strings.g.dart                        (const maps used at runtime; synchronous lookup)
//
// Keys keep their dotted shared names (e.g. `service.AEPS.name`) so the service registry can
// look labels up dynamically, exactly like the web client does.
import 'dart:convert';
import 'dart:io';

Map<String, String> parseTsDictionary(String source) {
  final out = <String, String>{};
  // 'key': 'value'  |  'key': "value"  (value may start on the next line)
  final re = RegExp(
    r"""'([A-Za-z0-9_.]+)'\s*:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")""",
    multiLine: true,
  );
  for (final m in re.allMatches(source)) {
    final raw = m.group(2) ?? m.group(3) ?? '';
    out[m.group(1)!] = raw.replaceAll(r"\'", "'").replaceAll(r'\"', '"').replaceAll(r'\n', '\n');
  }
  return out;
}

void main() {
  final root = File(Platform.script.toFilePath()).parent.parent;
  final shared = Directory('${root.path}/../../packages/shared/src/i18n');
  final en = parseTsDictionary(File('${shared.path}/en.ts').readAsStringSync());
  final hi = parseTsDictionary(File('${shared.path}/hi.ts').readAsStringSync());
  final mobileEn = (jsonDecode(File('${root.path}/tool/l10n/mobile_en.json').readAsStringSync()) as Map).cast<String, String>();
  final mobileHi = (jsonDecode(File('${root.path}/tool/l10n/mobile_hi.json').readAsStringSync()) as Map).cast<String, String>();

  final allEn = {...en, ...mobileEn};
  final allHi = {...hi, ...mobileHi};
  final missingHi = allEn.keys.where((k) => !allHi.containsKey(k)).toList();
  if (missingHi.isNotEmpty) {
    stderr.writeln('Missing Hindi translations for: ${missingHi.join(', ')}');
    exitCode = 1;
  }

  const encoder = JsonEncoder.withIndent('  ');
  File('${root.path}/lib/l10n/app_en.arb').writeAsStringSync('${encoder.convert({'@@locale': 'en', ...allEn})}\n');
  File('${root.path}/lib/l10n/app_hi.arb').writeAsStringSync('${encoder.convert({'@@locale': 'hi', ...allHi})}\n');

  String dartMap(Map<String, String> m) {
    final b = StringBuffer('{\n');
    for (final e in m.entries) {
      b.writeln('  ${_lit(e.key)}: ${_lit(e.value)},');
    }
    b.write('}');
    return b.toString();
  }

  File('${root.path}/lib/l10n/strings.g.dart').writeAsStringSync('''
// GENERATED by tool/sync_l10n.dart from lib/l10n/app_{en,hi}.arb — do not edit by hand.
// ignore_for_file: lines_longer_than_80_chars

const Map<String, String> stringsEn = ${dartMap(allEn)};

const Map<String, String> stringsHi = ${dartMap(allHi)};
''');
  stdout.writeln('en: ${allEn.length} keys, hi: ${allHi.length} keys (shared ${en.length}, mobile ${mobileEn.length})');
}

String _lit(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'";
